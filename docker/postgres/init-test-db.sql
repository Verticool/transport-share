-- Отдельная база для тестов.
--
-- Интеграционные проверки очищают таблицы перед каждым сценарием. Если запускать их против рабочей
-- базы, они стирают сессии и незакрытые поездки живых пользователей: вход перестаёт продлеваться
-- («пользователь не найден»), а самокат остаётся занятым без поездки. Поэтому у тестов своя база.
--
-- Скрипт выполняется один раз при создании тома (чистая установка). Для уже существующего тома
-- база создаётся вручную — команда указана в RUNBOOK.md.

CREATE DATABASE sharing_test OWNER sharing;
